/**
 * The deterministic business answers the Telegram bot gives.
 *
 * ## Reads belong to the services, not to the model
 *
 * Balances come from {@see ReceivablesService}; task scope from
 * `operational_tasks`; planillas from the sheet tables; documents from
 * `client_documents` and `client_document_requests`. Nothing is recomputed here
 * and nothing is generated by a language model, so the answer in Telegram and
 * the answer on the screen cannot disagree.
 *
 * ## Permission is checked here, against the same permission as the screen
 *
 * A chat is bound to one employee, and every method re-checks that employee's
 * permission before reading. A query outside the employee's reach returns a
 * refusal, not an empty list pretending there is nothing to see.
 *
 * ## Scope is not invented
 *
 * Tasks are the employee's own unless the employee holds `tasks.manage` and
 * explicitly asks for the whole team. Client searches require `clients.view`;
 * filtering by company additionally requires `relationships.view`, exactly as
 * the client list does. Document delivery requires `documents.view` and is
 * checked again on the concrete file, never on the request that mentions it.
 */
final class TelegramBusinessQueryService
{
    private const RESULT_LIMIT = 10;

    public function __construct(private readonly ReceivablesService $receivables) {}

    public function tasks(User $user, TelegramInterpretation $command): TelegramQueryResult
    {
        if ($user->cannot('tasks.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar tareas.');
        }

        $query = OperationalTask::query()
            ->with('assignee')
            ->whereIn('status', [TaskStatus::Pending->value, TaskStatus::InProgress->value]);

        $global = $command->globalScope && $user->can('tasks.manage');

        if (! $global) {
            $query->where('assigned_to', $user->id);
        }

        match ($command->dateScope) {
            'overdue' => $query->whereNotNull('due_on')->whereDate('due_on', '<', now()->toDateString()),
            'tomorrow' => $query->whereDate('due_on', now()->addDay()->toDateString()),
            'today' => $query->whereDate('due_on', '<=', now()->toDateString()),
            default => null,
        };

        $tasks = $query
            ->orderByRaw('due_on IS NULL')
            ->orderBy('due_on')
            ->orderBy('id')
            ->limit(self::RESULT_LIMIT)
            ->get();

        if ($tasks->isEmpty()) {
            return new TelegramQueryResult(match ($command->dateScope) {
                'overdue' => '📋 No tiene tareas vencidas pendientes.',
                'tomorrow' => '📋 No tiene tareas programadas para mañana.',
                'today' => '📋 No tiene tareas pendientes para hoy.',
                default => '📋 No tiene tareas pendientes asignadas.',
            });
        }

        $label = match ($command->dateScope) {
            'overdue' => 'Tareas vencidas',
            'tomorrow' => 'Tareas para mañana',
            'today' => 'Tareas para hoy',
            default => 'Tareas pendientes',
        };

        $lines = ["📋 {$label} ({$tasks->count()}):", ''];

        foreach ($tasks as $task) {
            $due = $task->due_on?->format('Y-m-d') ?? 'sin fecha';
            $line = "#{$task->id} · {$task->title}";
            $line .= "\n   Vence: {$due} · {$task->priority->label()}";

            if ($global && $task->assignee !== null) {
                $line .= " · Responsable: {$task->assignee->name}";
            }

            $lines[] = $line;
        }

        return new TelegramQueryResult(implode("\n", $lines));
    }

    public function reminders(User $user, TelegramInterpretation $command): TelegramQueryResult
    {
        if ($user->cannot('tasks.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar recordatorios.');
        }

        $query = OperationalTask::query()
            ->with('assignee')
            ->whereIn('status', [TaskStatus::Pending->value, TaskStatus::InProgress->value])
            ->whereNotNull('reminder_at')
            ->whereNull('reminder_dismissed_at')
            ->whereNull('completed_at')
            ->whereNull('cancelled_at');

        if (! ($command->globalScope && $user->can('tasks.manage'))) {
            $query->where('assigned_to', $user->id);
        }

        $tasks = $query->orderBy('reminder_at')->orderBy('id')->limit(self::RESULT_LIMIT)->get();

        if ($tasks->isEmpty()) {
            return new TelegramQueryResult('⏰ No tiene recordatorios pendientes.');
        }

        $lines = ["⏰ Recordatorios pendientes ({$tasks->count()}):", ''];

        foreach ($tasks as $task) {
            $when = $task->reminder_at?->format('Y-m-d H:i') ?? 'sin hora';
            $lines[] = "#{$task->id} · {$task->title}\n   Programado: {$when}";
        }

        return new TelegramQueryResult(implode("\n", $lines));
    }

    public function clients(User $user, TelegramInterpretation $command): TelegramQueryResult
    {
        if ($user->cannot('clients.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar clientes.');
        }

        $term = trim($command->query);

        if ($term === '') {
            $active = Client::query()->where('status', 'active')->count();

            return new TelegramQueryResult(
                "🏢 Clientes activos: {$active}\n\n"
                .'Para buscar uno: /clientes <nombre o documento>',
            );
        }

        $clients = $this->matchingClients($term, self::RESULT_LIMIT);

        if ($clients->isEmpty()) {
            return new TelegramQueryResult('🔎 No encontré clientes que coincidan con «'.$term.'».');
        }

        $lines = ['🔎 Clientes encontrados:', ''];
        $context = [];

        foreach ($clients as $client) {
            $lines[] = "#{$client->id} · {$client->fullName()}";
            $lines[] = '   '.$client->documentLabel().' · '.$client->status->label();
        }

        if ($clients->count() === 1) {
            $context = [
                'last_client_id' => (int) $clients->first()->id,
                'last_client_name' => $clients->first()->fullName(),
            ];
        }

        return new TelegramQueryResult(implode("\n", $lines), $context);
    }

    public function clientsByCompany(User $user, TelegramInterpretation $command): TelegramQueryResult
    {
        if ($user->cannot('clients.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar clientes.');
        }

        if ($user->cannot('relationships.view')) {
            return new TelegramQueryResult('⛔ Filtrar clientes por empresa requiere el permiso de relaciones.');
        }

        $term = trim((string) $command->company);

        if ($term === '') {
            return new TelegramQueryResult('Indique la empresa: «¿qué clientes pertenecen a la empresa X?».');
        }

        $companies = $this->matchingCompanies($term, 5);

        if ($companies->isEmpty()) {
            return new TelegramQueryResult('🔎 No encontré una empresa que coincida con «'.$term.'».');
        }

        if ($companies->count() > 1) {
            $lines = ['🔎 Varias empresas coinciden; indique una con más precisión:', ''];

            foreach ($companies as $company) {
                $lines[] = "#{$company->id} · {$company->displayName()}";
            }

            return new TelegramQueryResult(implode("\n", $lines));
        }

        $company = $companies->first();

        $clients = Client::query()
            ->whereHas('companyAssignments', fn (Builder $query) => $query
                ->where('company_id', $company->id)
                ->whereNull('ended_on'))
            ->orderBy('last_names')
            ->orderBy('first_names')
            ->limit(15)
            ->get(['id', 'first_names', 'last_names', 'document_type', 'document_number', 'status']);

        if ($clients->isEmpty()) {
            return new TelegramQueryResult('🏢 La empresa '.$company->displayName().' no tiene clientes activos asociados.');
        }

        $lines = ["🏢 Clientes de {$company->displayName()} ({$clients->count()}):", ''];

        foreach ($clients as $client) {
            $lines[] = "#{$client->id} · {$client->fullName()} · {$client->documentLabel()}";
        }

        return new TelegramQueryResult(implode("\n", $lines));
    }

    public function clientAccount(User $user, TelegramInterpretation $command): TelegramQueryResult
    {
        if ($user->cannot('receivables.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar cartera.');
        }

        if ($user->cannot('clients.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar clientes.');
        }

        $term = trim($command->query);

        if ($term === '') {
            return new TelegramQueryResult('Indique el cliente: «¿cuál es la deuda de Juan Pérez?».');
        }

        $clients = $this->matchingClients($term, 5);

        if ($clients->isEmpty()) {
            return new TelegramQueryResult('🔎 No encontré un cliente que coincida con «'.$term.'».');
        }

        if ($clients->count() > 1) {
            $lines = ['🔎 Varios clientes coinciden; indique cuál:', ''];

            foreach ($clients as $client) {
                $lines[] = "#{$client->id} · {$client->fullName()} · {$client->documentLabel()}";
            }

            return new TelegramQueryResult(implode("\n", $lines));
        }

        $client = $clients->first();
        $account = $this->receivables->clientAccount($client);
        $summary = $account['summary'];

        $lines = [
            "💳 Cuenta de {$client->fullName()}",
            '',
            'Saldo pendiente: $'.number_format((int) $summary['outstanding_balance_cop'], 0, ',', '.'),
            'Saldo vencido: $'.number_format((int) $summary['overdue_balance_cop'], 0, ',', '.'),
            'Obligaciones abiertas: '.(int) $summary['open_obligations_count'],
            'Meses adeudados: '.((int) $summary['overdue_periods_count'] > 0
                ? implode(', ', $summary['owed_periods'])
                : 'ninguno'),
            'Semáforo: '.$summary['traffic_light_label'],
        ];

        return new TelegramQueryResult(implode("\n", $lines), [
            'last_client_id' => (int) $client->id,
            'last_client_name' => $client->fullName(),
        ]);
    }

    public function receivables(User $user): TelegramQueryResult
    {
        if ($user->cannot('receivables.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar cartera.');
        }

        $page = $this->receivables->list(['overdue' => true], 1, 5);
        $summary = $page['summary'];

        $lines = [
            '💳 Cartera vencida al '.now()->format('Y-m-d').':',
            '',
            'Saldo vencido: $'.number_format((int) $summary['overdue_balance_cop'], 0, ',', '.'),
            'Saldo pendiente total: $'.number_format((int) $summary['outstanding_balance_cop'], 0, ',', '.'),
            'Clientes con deuda: '.(int) $summary['clients_with_debt'],
            'Obligaciones vencidas: '.(int) $summary['overdue_obligations_count'],
        ];

        if ($page['items'] !== []) {
            $lines[] = '';
            $lines[] = 'Mayores saldos vencidos:';

            foreach ($page['items'] as $row) {
                $lines[] = '· '.$row['full_name'].' — $'.number_format((int) $row['overdue_balance_cop'], 0, ',', '.');
            }
        }

        return new TelegramQueryResult(implode("\n", $lines));
    }

    public function sheets(User $user, TelegramInterpretation $command): TelegramQueryResult
    {
        if ($user->cannot('planillas.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar planillas.');
        }

        $period = $command->period ?? now()->format('Y-m');
        $month = $period.'-01';

        $base = ContributionSheet::query()
            ->with(['company', 'period'])
            ->whereHas('period', fn (Builder $query) => $query->whereDate('period_month', $month));

        $statuses = match ($command->sheetStatus) {
            'unpaid' => [ContributionSheetStatus::Draft, ContributionSheetStatus::Ready, ContributionSheetStatus::Submitted],
            'paid' => [ContributionSheetStatus::Paid],
            'cancelled' => [ContributionSheetStatus::Cancelled],
            'draft' => [ContributionSheetStatus::Draft],
            'ready' => [ContributionSheetStatus::Ready],
            'submitted' => [ContributionSheetStatus::Submitted],
            default => null,
        };

        if ($statuses !== null) {
            $base->whereIn('status', array_map(fn (ContributionSheetStatus $status): string => $status->value, $statuses));
        }

        $total = (clone $base)->count();
        $sheets = (clone $base)
            ->orderBy('sheet_number')
            ->orderBy('id')
            ->limit(self::RESULT_LIMIT)
            ->get();

        if ($total === 0) {
            return new TelegramQueryResult(
                '📅 No hay planillas'.($command->sheetStatus === 'unpaid' ? ' pendientes de pago' : '')
                .' para '.$period.'.',
            );
        }

        $title = match ($command->sheetStatus) {
            'unpaid' => 'Planillas que faltan por pagar',
            'paid' => 'Planillas pagadas',
            'cancelled' => 'Planillas canceladas',
            'draft' => 'Planillas en borrador',
            'ready' => 'Planillas listas',
            'submitted' => 'Planillas enviadas',
            default => 'Planillas',
        };

        $lines = ["📅 {$title} de {$period} ({$total}):", ''];

        foreach ($sheets as $sheet) {
            $company = $sheet->company?->displayName() ?? 'Sin empresa';
            $number = $sheet->sheet_number !== null ? '#'.$sheet->sheet_number.' · ' : '';
            $lines[] = "{$number}{$company} · {$sheet->status->label()}";
        }

        if ($total > $sheets->count()) {
            $lines[] = '';
            $lines[] = 'Mostrando '.$sheets->count().' de '.$total.'.';
        }

        return new TelegramQueryResult(implode("\n", $lines));
    }

    public function documents(User $user, TelegramInterpretation $command): TelegramQueryResult
    {
        if ($user->cannot('documents.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar documentos.');
        }

        if ($command->documentId !== null) {
            $document = ClientDocument::query()
                ->with(['client', 'documentType'])
                ->whereKey($command->documentId)
                ->whereNull('archived_at')
                ->first();

            if ($document === null) {
                return new TelegramQueryResult('🔎 No encontré un documento activo con ese número.');
            }

            return new TelegramQueryResult(
                $this->describeDocument($document),
                $this->documentContext($document),
            );
        }

        $term = trim($command->query);

        if ($term !== '') {
            if ($command->pendingOnly) {
                if ($user->cannot('clients.view')) {
                    return new TelegramQueryResult('⛔ Resolver el cliente requiere permiso para consultar clientes.');
                }

                $client = $this->singleClient($term);

                if ($client === null) {
                    return new TelegramQueryResult('🔎 No encontré un cliente que coincida con «'.$term.'».');
                }

                return $this->pendingDocumentRequests($client);
            }

            return $this->documentsForClient($user, $term);
        }

        return $this->pendingDocumentRequests();
    }

    public function sendDocument(User $user, TelegramInterpretation $command): TelegramQueryResult
    {
        if ($user->cannot('documents.view')) {
            return new TelegramQueryResult('⛔ Su cuenta no tiene permiso para consultar documentos.');
        }

        $document = null;

        if ($command->documentId !== null) {
            $document = ClientDocument::query()
                ->with(['client', 'documentType'])
                ->whereKey($command->documentId)
                ->whereNull('archived_at')
                ->first();

            if ($document === null) {
                return new TelegramQueryResult('🔎 No encontré un documento activo con ese número.');
            }
        }

        $term = trim($command->query);

        if ($document !== null && $term !== '') {
            $client = $this->singleClient($term);

            if ($client === null) {
                return new TelegramQueryResult('🔎 No encontré un cliente que coincida con «'.$term.'».');
            }

            if ((int) $document->client_id !== (int) $client->id) {
                return new TelegramQueryResult('⛔ El documento indicado no pertenece al cliente solicitado.');
            }
        }

        if ($document === null && $term !== '') {
            $client = $this->singleClient($term);

            if ($client === null) {
                return new TelegramQueryResult('🔎 No encontré un cliente que coincida con «'.$term.'».');
            }

            $query = ClientDocument::query()
                ->with(['client', 'documentType'])
                ->where('client_id', $client->id)
                ->whereNull('archived_at')
                ->orderByDesc('created_at')
                ->orderByDesc('id');

            if ($command->approvedOnly) {
                $query->where('review_status', 'approved');
            }

            $document = $query->first();

            if ($document === null) {
                return new TelegramQueryResult('📄 Ese cliente no tiene un documento autorizado para entregar.');
            }
        }

        if ($document === null) {
            return new TelegramQueryResult('Indique qué documento desea: «envíame el documento del cliente Juan Pérez».');
        }

        return new TelegramQueryResult(
            'FILE:'.(int) $document->id,
            $this->documentContext($document),
        );
    }

    /**
     * Resolve the one client a sentence names, or null when it is absent/ambiguous.
     */
    public function singleClient(string $term): ?Client
    {
        $clients = $this->matchingClients($term, 2);

        return $clients->count() === 1 ? $clients->first() : null;
    }

    /**
     * @return Collection<int, Client>
     */
    private function matchingClients(string $term, int $limit): Collection
    {
        if (preg_match('/^id:(\d+)$/', $term, $matches) === 1) {
            return Client::query()
                ->whereKey((int) $matches[1])
                ->limit(1)
                ->get();
        }

        $pattern = SafeSearch::likeNeedle($term);
        $compact = mb_strtolower(str_replace(['.', ' ', '-'], '', $term));
        $compactPattern = $compact === mb_strtolower($term) ? null : SafeSearch::likeNeedle($compact);

        return Client::query()
            ->where(function (Builder $query) use ($pattern, $compactPattern): void {
                $query->whereRaw(SafeSearch::match('first_names'), [$pattern])
                    ->orWhereRaw(SafeSearch::match('last_names'), [$pattern])
                    ->orWhereRaw(SafeSearch::match("concat_ws(' ', first_names, last_names)"), [$pattern])
                    ->orWhereRaw(SafeSearch::match('document_number'), [$pattern]);

                if ($compactPattern !== null) {
                    $query->orWhereRaw(SafeSearch::match('document_number'), [$compactPattern]);
                }
            })
            ->orderBy('last_names')
            ->orderBy('first_names')
            ->limit($limit)
            ->get();
    }

    /**
     * @return Collection<int, Company>
     */
    private function matchingCompanies(string $term, int $limit): Collection
    {
        $pattern = SafeSearch::likeNeedle($term);

        return Company::query()
            ->where(function (Builder $query) use ($pattern): void {
                $query->whereRaw(SafeSearch::match('legal_name'), [$pattern])
                    ->orWhereRaw(SafeSearch::match("coalesce(trade_name, '')"), [$pattern])
                    ->orWhereRaw(SafeSearch::match("concat_ws(' ', coalesce(trade_name, ''), legal_name)"), [$pattern]);
            })
            ->orderBy('legal_name')
            ->limit($limit)
            ->get();
    }

    private function documentsForClient(User $user, string $term): TelegramQueryResult
    {
        if ($user->cannot('clients.view')) {
            return new TelegramQueryResult('⛔ Resolver el cliente requiere permiso para consultar clientes.');
        }

        $client = $this->singleClient($term);

        if ($client === null) {
            return new TelegramQueryResult('🔎 No encontré un cliente que coincida con «'.$term.'».');
        }

        $documents = ClientDocument::query()
            ->with('documentType')
            ->where('client_id', $client->id)
            ->whereNull('archived_at')
            ->orderByDesc('created_at')
            ->orderByDesc('id')
            ->limit(self::RESULT_LIMIT)
            ->get();

        if ($documents->isEmpty()) {
            return new TelegramQueryResult('📄 '.$client->fullName().' no tiene documentos activos.');
        }

        $lines = ["📄 Documentos de {$client->fullName()} ({$documents->count()}):", ''];

        foreach ($documents as $document) {
            $type = $document->documentType?->name ?? 'Documento';
            $lines[] = "#{$document->id} · {$document->title}";
            $lines[] = "   {$type} · {$document->review_status->label()}";
        }

        $context = [
            'last_client_id' => (int) $client->id,
            'last_client_name' => $client->fullName(),
        ];

        if ($documents->count() === 1) {
            $context['last_document_id'] = (int) $documents->first()->id;
        }

        return new TelegramQueryResult(implode("\n", $lines), $context);
    }

    private function pendingDocumentRequests(?Client $client = null): TelegramQueryResult
    {
        $query = ClientDocumentRequest::query()
            ->with(['client', 'documentType'])
            ->whereNotIn('status', [
                DocumentRequestStatus::Approved->value,
                DocumentRequestStatus::Cancelled->value,
            ]);

        if ($client !== null) {
            $query->where('client_id', $client->id);
        }

        $total = (clone $query)->count();
        $requests = $query->orderBy('due_on')->orderBy('id')->limit(self::RESULT_LIMIT)->get();

        if ($total === 0) {
            return new TelegramQueryResult('📄 No hay solicitudes de documentos pendientes.');
        }

        $title = $client === null
            ? 'Solicitudes de documentos pendientes'
            : 'Solicitudes pendientes de '.$client->fullName();

        $lines = ["📄 {$title} ({$total}):", ''];

        foreach ($requests as $request) {
            $due = $request->due_on?->format('Y-m-d') ?? 'sin fecha';
            $name = $request->client?->fullName() ?? 'Cliente';
            $lines[] = "#{$request->id} · {$request->title}";
            $lines[] = "   {$name} · {$request->status->label()} · vence {$due}";
        }

        if ($total > $requests->count()) {
            $lines[] = '';
            $lines[] = 'Mostrando '.$requests->count().' de '.$total.'.';
        }

        return new TelegramQueryResult(implode("\n", $lines));
    }

    /**
     * @return array<string, mixed>
     */
    private function documentContext(ClientDocument $document): array
    {
        return [
            'last_document_id' => (int) $document->id,
            'last_client_id' => (int) $document->client_id,
            'last_client_name' => $document->client?->fullName(),
        ];
    }

    private function describeDocument(ClientDocument $document): string
    {
        $lines = [
            "📄 Documento #{$document->id}",
            '',
            'Título: '.$document->title,
            'Cliente: '.($document->client?->fullName() ?? '—'),
            'Tipo: '.($document->documentType?->name ?? '—'),
            'Estado: '.$document->review_status->label(),
        ];

        if ($document->archived_at !== null) {
            $lines[] = 'Archivado: sí';
        }

        return implode("\n", $lines);
    }
}
