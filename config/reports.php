<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Scheduled report lease
    |--------------------------------------------------------------------------
    |
    | How long a claimed occurrence of a report schedule stays claimed.
    |
    | The occurrence is generated by the scheduler process (`schedule:work`,
    | `reports:run-schedules`), which has no time limit of its own: the CLI
    | runs with `max_execution_time = 0`. The lease therefore has to be longer
    | than the longest *legitimate* generation — a full portfolio workbook or
    | a PDF over every client — or the scheduler would take a live occurrence
    | away from the process that is still working on it.
    |
    | The lease is not the only guarantee. The claim carries a fencing token,
    | so an executor whose lease expired while it was working still cannot
    | overwrite the result of the executor that took the occurrence over, and
    | the artifact is unique per occurrence, so a duplicate execution cannot
    | produce a second report. The lease is what detects a dead executor; the
    | token is what makes the recovery safe.
    |
    | The documented worker timeouts are 180 s (default, support,
    | notifications, automations), 330 s (ai-tasks) and 630 s (imports). The
    | default below is comfortably above the largest of them.
    |
    */

    'schedule_lease_seconds' => (int) env('REPORT_SCHEDULE_LEASE_SECONDS', 1800),

];
